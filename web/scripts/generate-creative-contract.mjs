import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const contractPath = path.join(root, "contracts/creative-v1.json");
const outputPath = path.join(root, "web/src/services/api/generated/creative-contract.ts");
const contract = JSON.parse(await readFile(contractPath, "utf8"));
const enums = contract["x-fyjit-enums"];
const operations = Object.fromEntries(Object.entries(contract.paths).flatMap(([route, methods]) => Object.entries(methods).map(([method, operation]) => [operation.operationId, { method: method.toUpperCase(), path: route }])));
const union = (values) => values.map((value) => JSON.stringify(value)).join(" | ");
const source = `// Generated by scripts/generate-creative-contract.mjs. Do not edit.\n` +
    `export const CREATIVE_CONTRACT_VERSION = ${JSON.stringify(contract["x-fyjit-contract-version"])} as const;\n` +
    `export const CREATIVE_OPERATIONS = ${JSON.stringify(operations, null, 4)} as const;\n` +
    `export type CreativeCapability = ${union(enums.capability)};\n` +
    `export type CreativeJobStatusContract = ${union(enums.jobStatus)};\n` +
    `export type CreativeAssetTypeContract = ${union(enums.assetType)};\n`;

if (process.argv.includes("--check")) {
    const existing = await readFile(outputPath, "utf8").catch(() => "");
    if (existing !== source) {
        console.error("Creative contract client is stale. Run: bun run contract:generate");
        process.exitCode = 1;
    }
} else {
    await writeFile(outputPath, source, "utf8");
}
